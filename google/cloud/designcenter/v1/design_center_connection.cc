std::shared_ptr<DesignCenterConnection> MakeDesignCenterConnection(
    Options options) {
  internal::CheckExpectedOptions<CommonOptionList, GrpcOptionList,
                                 UnifiedCredentialsOptionList,
                                 DesignCenterPolicyOptionList>(options,
                                                               __func__);
  options =
      designcenter_v1_internal::DesignCenterDefaultOptions(std::move(options));
  auto background = internal::MakeBackgroundThreadsFactory(options)();
  auto auth = internal::CreateAuthenticationStrategy(background->cq(), options);
  auto stub = designcenter_v1_internal::CreateDefaultDesignCenterStub(
      std::move(auth), options);
  return designcenter_v1_internal::MakeDesignCenterTracingConnection(
      std::make_shared<designcenter_v1_internal::DesignCenterConnectionImpl>(
          std::move(background), std::move(stub), std::move(options)));
}

